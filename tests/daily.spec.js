// Unit tests for the daily backlog rules in .github/scripts/daily.js (no browser needed).
const { test, expect } = require('@playwright/test');
const d = require('../.github/scripts/daily.js');

const NOW = new Date('2026-11-14T12:30:00Z'); // Saturday 07:30 in New York
const hoursAgo = (h) => new Date(NOW.getTime() - h * 3600 * 1000);
const issue = (number, labels = ['task', 'proposed'], over = {}) => ({
  number, state: 'open', labels: labels.map((name) => ({ name })), created_at: '2026-11-01T00:00:00Z', ...over,
});
const owner = (body) => ({ body, author_association: 'OWNER', user: { login: 'Hitoshi85' } });
const cand = (number, h, labels, comments = []) => ({ issue: issue(number, labels), comments, since: hoursAgo(h) });

test('the veto window starts when the proposed label was added', () => {
  const events = [
    { event: 'labeled', label: { name: 'task' }, created_at: '2026-11-02T00:00:00Z' },
    { event: 'labeled', label: { name: 'proposed' }, created_at: '2026-11-03T00:00:00Z' },
  ];
  expect(d.proposedAt(issue(1), events).toISOString()).toBe('2026-11-03T00:00:00.000Z');
  expect(d.proposedAt(issue(1), []).toISOString()).toBe('2026-11-01T00:00:00.000Z');
});

test('a proposed task is promoted only after 36 hours with no veto', () => {
  expect(d.vetoReason(issue(1), [], hoursAgo(35), NOW)).toMatch(/veto window/);
  expect(d.vetoReason(issue(1), [], hoursAgo(36), NOW)).toBeNull();
  expect(d.vetoReason(issue(1, ['task', 'proposed', 'hold']), [], hoursAgo(50), NOW)).toMatch(/hold/);
  // Controls, modes, the route or prod: waits for the owner's yes.
  expect(d.vetoReason(issue(1, ['task', 'proposed', 'needs-yes']), [], hoursAgo(50), NOW)).toMatch(/needs-yes/);
  expect(d.vetoReason(issue(1, ['task']), [], hoursAgo(50), NOW)).toMatch(/not labelled/);
  expect(d.vetoReason(issue(1, ['task', 'proposed', 'ready']), [], hoursAgo(50), NOW)).toMatch(/already/);
  expect(d.vetoReason(issue(1, ['task', 'proposed'], { state: 'closed' }), [], hoursAgo(50), NOW)).toBe('closed');
});

test('"no" or "drop" from the owner vetoes; others and mentions do not', () => {
  const since = hoursAgo(50);
  expect(d.vetoReason(issue(1), [owner('drop #1')], since, NOW)).toMatch(/said no/);
  expect(d.vetoReason(issue(1), [owner('No, not this one')], since, NOW)).toMatch(/said no/);
  expect(d.vetoReason(issue(1), [owner('Looks good, nothing to drop here')], since, NOW)).toBeNull();
  expect(d.vetoReason(issue(1), [owner('Nothing against it')], since, NOW)).toBeNull();
  expect(d.vetoReason(issue(1), [owner('No problem, go ahead')], since, NOW)).toBeNull();
  expect(d.vetoReason(issue(1), [owner('no')], since, NOW)).toMatch(/said no/);
  expect(d.vetoReason(issue(1), [owner('Drop.')], since, NOW)).toMatch(/said no/);
  for (const v of ['No thanks', 'Drop it', 'Nope', 'no.', 'NO WAY']) expect(d.vetoReason(issue(1), [owner(v)], since, NOW), v).toMatch(/said no/);
  for (const ok of ['No worries, go ahead', 'no problems here', 'Nothing to add']) expect(d.vetoReason(issue(1), [owner(ok)], since, NOW), ok).toBeNull();
  // Claude posts from the owner's account; its comments carry the footer and never veto.
  expect(d.vetoReason(issue(1), [owner('No problems found.\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_')], since, NOW)).toBeNull();
  expect(d.vetoReason(issue(1), [{ body: 'no', author_association: 'NONE', user: { login: 'x' } }], since, NOW)).toBeNull();
  expect(d.vetoReason(issue(1), [{ body: 'drop', author_association: 'OWNER', user: { login: 'github-actions[bot]' } }], since, NOW)).toBeNull();
});

test('at most 3 a day, oldest first', () => {
  const cands = [cand(5, 40), cand(2, 90), cand(3, 80), cand(4, 70), cand(6, 10), cand(7, 100, ['task', 'proposed', 'hold'])];
  const r = d.promotions(cands, NOW);
  expect(r.promote).toEqual([2, 3, 4]);
  expect(r.skipped.find((s) => s.number === 5).reason).toMatch(/daily limit/);
  expect(r.skipped.find((s) => s.number === 6).reason).toMatch(/veto window/);
  expect(r.skipped.find((s) => s.number === 7).reason).toMatch(/hold/);
  // Two already promoted in the last 24 h leave room for one.
  expect(d.promotions(cands, NOW, 2).promote).toEqual([2]);
  expect(d.promotions(cands, NOW, 3).promote).toEqual([]);
});

test('counts promotions from the last 24 hours only', () => {
  const marker = (h) => ({ body: `now ready ${d.PROMOTED_MARKER}`, created_at: hoursAgo(h).toISOString() });
  expect(d.countPromoted([[marker(2)], [marker(30)], [{ body: 'hi', created_at: hoursAgo(1).toISOString() }], [marker(23)]], NOW)).toBe(2);
});

test('the report is written on Fridays in New York time', () => {
  expect(d.isReportDay(new Date('2026-11-13T12:30:00Z'))).toBe(true); // Fri 07:30 EST
  expect(d.isReportDay(new Date('2026-11-14T03:00:00Z'))).toBe(true); // Fri 22:00 EST (already Saturday in UTC)
  expect(d.isReportDay(new Date('2026-11-13T04:00:00Z'))).toBe(false); // Thu 23:00 EST
  expect(d.isReportDay(new Date('2026-07-10T11:30:00Z'))).toBe(true); // Fri 07:30 EDT in summer
  expect(d.localDay(new Date('2026-11-14T03:00:00Z')).date).toBe('2026-11-13');
});

test('weekly numbers', () => {
  const merged = [
    { files: [{ filename: 'game.js' }], mergedBy: 'github-actions[bot]', mergedAt: '2026-11-10T10:00:00Z', readyAt: '2026-11-10T00:00:00Z' },
    { files: [{ filename: 'docs/WORKFLOW.md' }], mergedBy: 'Hitoshi85', mergedAt: '2026-11-11T00:00:00Z', readyAt: null },
    { files: [{ filename: 'style.css' }], mergedBy: 'github-actions[bot]', mergedAt: '2026-11-12T20:00:00Z', readyAt: '2026-11-12T00:00:00Z' },
    { files: [{ filename: 'tests/a.spec.js' }], mergedBy: 'github-actions[bot]', mergedAt: '2026-11-12T00:00:00Z', readyAt: null },
  ];
  expect(d.metrics(merged, 6)).toEqual({
    messagesPerPr: 1.5, mergedWithoutOwner: 3, leadTimeHours: 15, playerFacingShare: 50, merged: 4,
  });
  expect(d.metrics([], 2)).toEqual({ messagesPerPr: null, mergedWithoutOwner: 0, leadTimeHours: null, playerFacingShare: null, merged: 0 });
  expect(d.closesIssue('Does it.\n\nCloses #41, closes #42')).toBe(41);
  expect(d.closesIssue('No issue')).toBeNull();
});

test('reads owner messages and play links from the repo files', () => {
  const md = [
    '## 2. Shipped changes', '| 2026-11-10 | not feedback | x |',
    '## 3. Feedback log', '| Date | Feedback | Outcome |', '|---|---|---|',
    '| 2026-11-06 | old | x |', '| 2026-11-07 | in | x |', '| 2026-11-10 | in | x |', '| 2026-11-14 | later | x |',
    '## 4. Open backlog', '| 2026-11-10 | not feedback | x |',
  ].join('\n');
  expect(d.feedbackRows(md, '2026-11-07', '2026-11-13')).toBe(2);
  const archive = '# x\n## Feedback log, older rows\n| 2026-11-08 | a | b |\n| 2026-11-01 | a | b |\n## Shipped changes up to 2026-11-10\n| 2026-11-08 | c | d |\n';
  expect(d.feedbackRows(archive, '2026-11-07', '2026-11-13')).toBe(1);
  const readme = '# x\n<!-- play-links:start -->\n- **Prod** (prod-2, abc): https://p/\n- **Dev** (def): https://p/dev/\n<!-- play-links:end -->\n';
  expect(d.playLinks(readme)).toBe('- **Prod** (prod-2, abc): https://p/\n- **Dev** (def): https://p/dev/');
});

test('report body has every section and the 4 numbers', () => {
  const body = d.reportBody({
    weekOf: '2026-11-13', shipped: ['#50 Something'], proposed: [], blocked: ['#9 Big (needs-yes)'],
    links: '- **Dev** (abc): https://p/dev/',
    numbers: { messagesPerPr: 1.5, mergedWithoutOwner: 3, leadTimeHours: null, playerFacingShare: 50, merged: 4 },
  });
  for (const s of ['## Shipped to dev', '## Proposed', '## Blocked or waiting', '## Play links', '## Numbers']) expect(body).toContain(s);
  expect(body).toContain('#50 Something');
  expect(body).toContain('Nothing proposed.');
  expect(body).toContain('| 3 of 4 |');
  expect(body).toContain('| n/a |');
  expect(body).toContain('| 50% |');
});
